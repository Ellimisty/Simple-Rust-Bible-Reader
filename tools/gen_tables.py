#!/usr/bin/env python3
"""Generate Rust data tables from the upstream C# sources.

Usage: tools/gen_tables.py <path to SimpleBibleReader 5.6.2 source dir>
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent / "crates/sbr-core/src"
header = "// @generated by tools/gen_tables.py from the upstream {} -- do not edit.\n\n"


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def versification():
    text = (src / "SwordVersification.cs").read_text(encoding="utf-8-sig")
    body = text[: text.index("public static string[] getVersifications")]
    toks = []
    for m in re.finditer(r'"([^"]*)"|new int\[\]\{([^}]*)\}', body):
        if m.group(1) is not None:
            toks.append(m.group(1))
        else:
            toks.append([int(x) for x in m.group(2).replace(",", " ").split()])
    vs, i = [], 0
    while i < len(toks):
        t = toks[i]
        if isinstance(t, str) and i + 2 < len(toks) and isinstance(toks[i + 1], str) and isinstance(toks[i + 2], list):
            vs[-1][1][-1][1].append((t, toks[i + 1], toks[i + 2]))
            i += 3
        elif t in ("ot", "nt"):
            vs[-1][1].append((t, []))
            i += 1
        else:
            assert isinstance(t, str), t
            vs.append((t, []))
            i += 1
    out = [header.format("SwordVersification.cs"), "use super::{Book, Versification};\n\n"]
    out.append("#[rustfmt::skip]\npub static VERSIFICATIONS: &[Versification] = &[\n")
    for name, tests in vs:
        assert [t for t, _ in tests] == ["ot", "nt"], (name, [t for t, _ in tests])
        out.append(f"    Versification {{\n        name: {rs_str(name)},\n")
        for t, books in tests:
            out.append(f"        {t}: &[\n")
            for bn, ab, ch in books:
                out.append(f"            Book {{ name: {rs_str(bn)}, abbr: {rs_str(ab)}, chapters: &[{', '.join(map(str, ch))}] }},\n")
            out.append("        ],\n")
        out.append("    },\n")
    out.append("];\n")
    (root / "versification/data.rs").write_text("".join(out))
    print("versifications:", len(vs))


def chapter_headings():
    text = (src / "ChapterHeadingUtil.cs").read_text(encoding="utf-8-sig")
    entries = {}
    for m in re.finditer(r'map\.Add\("(\d+)\.(\d+)", "([^"]*)"\);', text):
        key = (int(m.group(1)), int(m.group(2)))
        assert key not in entries, key
        entries[key] = m.group(3)
    out = [header.format("ChapterHeadingUtil.cs")]
    out.append("/// `(book, chapter, title)`, sorted by `(book, chapter)`.\n")
    out.append("#[rustfmt::skip]\npub static TITLES: &[(u16, u16, &str)] = &[\n")
    for (b, c), t in sorted(entries.items()):
        out.append(f"    ({b}, {c}, {rs_str(t)}),\n")
    out.append("];\n")
    (root / "chapter_heading/data.rs").write_text("".join(out))
    print("chapter titles:", len(entries))


versification()
chapter_headings()
